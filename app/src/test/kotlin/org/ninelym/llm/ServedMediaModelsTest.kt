package org.ninelym.llm

import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test
import org.ninelym.ai.ImageGenerationResult
import org.ninelym.ai.LocalImageGenerator
import org.ninelym.aid.core.AIDResult
import org.ninelym.aid.core.AIDTensor
import org.ninelym.aid.endpoint.VoiceEndpoint
import org.ninelym.aid.hub.EndpointRequest
import java.io.File

/**
 * Speech and image paths against real served models (Whisper-compatible transcription,
 * TTS, Stable Diffusion) at TOGAI_MEDIA_BASE_URL; skipped when that isn't set.
 */
class ServedMediaModelsTest {

    private val baseUrl = System.getenv("TOGAI_MEDIA_BASE_URL")

    private fun media(): OpenAICompatibleModel {
        assumeTrue("TOGAI_MEDIA_BASE_URL not set; no served speech/image models", baseUrl != null)
        return OpenAICompatibleModel(ModelEndpointConfig(baseUrl!!, "stable-diffusion", timeoutSeconds = 600))
    }

    @Test
    fun `speech synthesized by the TTS model is transcribed back by the speech model`() = runBlocking {
        val endpoint = media()
        val audio = endpoint.speech("The weather is sunny and warm today.").getOrThrow()
        assertEquals("RIFF", String(audio.copyOfRange(0, 4)))

        val file = File.createTempFile("tts", ".wav").apply { writeBytes(audio); deleteOnExit() }
        val heard = endpoint.transcribe(file).getOrThrow().lowercase()
        assertTrue("transcript was: $heard", "sunny" in heard || "weather" in heard)
    }

    @Test
    fun `AID voice endpoint synthesizes and transcribes with the served models`() = runBlocking {
        val endpoint = media()
        val voice = VoiceEndpoint({ Result.success(endpoint) })
        assertTrue(voice.initialize() is AIDResult.Success)

        val spoken = voice.handle(
            EndpointRequest(action = "synthesize", payload = null, parameters = mapOf("text" to "Good morning, friend.")),
            AIDTensor.neutral()
        )
        val path = ((spoken as AIDResult.Success).data as Map<*, *>)["audioPath"] as String
        val heard = voice.handle(
            EndpointRequest(action = "transcribe", payload = null, parameters = mapOf("audioPath" to path)),
            AIDTensor.neutral()
        )
        val text = (((heard as AIDResult.Success).data as Map<*, *>)["transcription"] as String).lowercase()
        assertTrue("transcript was: $text", "morning" in text)
    }

    @Test
    fun `image generator returns a PNG rendered by the served diffusion model`() = runBlocking {
        val endpoint = media()
        val generator = LocalImageGenerator({ Result.success(endpoint) })
        assertTrue(generator.initialize())

        val result = generator.generateWithQuality("a red apple on a wooden table", org.ninelym.ai.QualityLevel.DRAFT)
        assertTrue("generation failed: $result", result is ImageGenerationResult.Success)
        val bytes = (result as ImageGenerationResult.Success).image.imageData
        // PNG signature, then IHDR width/height (big-endian) at offsets 16 and 20
        assertEquals("PNG", String(bytes.copyOfRange(1, 4)))
        val buf = java.nio.ByteBuffer.wrap(bytes)
        assertEquals(512, buf.getInt(16))
        assertEquals(512, buf.getInt(20))
        // A real render isn't a flat image: pixel data must compress to well over a kilobyte
        assertTrue(bytes.size > 10_000)
    }

    @Test
    fun `vision model describes an image generated by the diffusion model`() = runBlocking {
        val media = media()
        val visionUrl = System.getenv("TOGAI_VISION_BASE_URL")
        assumeTrue("TOGAI_VISION_BASE_URL not set; no served vision model", visionUrl != null)
        val vision = OpenAICompatibleModel(ModelEndpointConfig(visionUrl!!, System.getenv("TOGAI_VISION_MODEL") ?: "nanollava", timeoutSeconds = 600))

        val png = media.generateImage("a red apple on a wooden table", "512x512", "stable-diffusion").getOrThrow()
        val file = File.createTempFile("apple", ".png").apply { writeBytes(png); deleteOnExit() }

        val endpoint = org.ninelym.aid.endpoint.ImageEndpoint({ Result.success(vision) })
        assertTrue(endpoint.initialize() is AIDResult.Success)
        val analyzed = endpoint.handle(
            EndpointRequest(action = "analyze", payload = null,
                parameters = mapOf("imagePath" to file.path, "prompt" to "What fruit is in this picture?")),
            AIDTensor.neutral()
        )
        val description = (((analyzed as AIDResult.Success).data as Map<*, *>)["description"] as String).lowercase()
        assertTrue("description was: $description", "apple" in description)
    }
}
