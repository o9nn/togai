package org.ninelym.llm

import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test

/**
 * Talks to a real, running model server. Set TOGAI_LLM_BASE_URL (e.g. http://127.0.0.1:8080/v1)
 * and TOGAI_LLM_MODEL; without them the live tests are not run, since there is no fake model.
 */
class OpenAICompatibleModelTest {

    private val config = ModelEndpointConfig.fromEnvironment()

    private fun liveModel(): OpenAICompatibleModel {
        assumeTrue("TOGAI_LLM_BASE_URL/TOGAI_LLM_MODEL not set; no live model to test against", config != null)
        return OpenAICompatibleModel(config!!)
    }

    @Test
    fun `chat returns text generated by the live model`() = runBlocking {
        val reply = liveModel().ask("You answer briefly.", "Name one primary colour.",
            GenerationOptions(maxTokens = 20, temperature = 0f)).getOrThrow()
        assertTrue("expected non-blank model output", reply.isNotBlank())
    }

    @Test
    fun `streaming delivers multiple chunks that make up the reply`() = runBlocking {
        val chunks = mutableListOf<String>()
        val reply = liveModel().ask("You answer briefly.", "Count from one to five in words.",
            GenerationOptions(maxTokens = 40, temperature = 0f)) { chunks += it }.getOrThrow()
        assertTrue("expected the server to stream more than one chunk", chunks.size > 1)
        assertEquals(reply, chunks.joinToString(""))
    }

    @Test
    fun `listModels reports the served model`() = runBlocking {
        val model = liveModel()
        assertTrue(model.listModels().getOrThrow().contains(model.modelId))
    }

    @Test
    fun `an unreachable server is a failure, not a fallback reply`() = runBlocking {
        val dead = OpenAICompatibleModel(ModelEndpointConfig("http://127.0.0.1:1/v1", "none", timeoutSeconds = 2))
        assertTrue(dead.ask("s", "u").isFailure)
    }
}
